/// Represents the input for an authentication method.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", content = "data")]
pub enum AuthInput {
    /// Password-based authentication.
    Password {
        /// The username or email.
        identifier: String,
        /// The secret password.
        password: String,
    },
    /// OAuth2/OIDC authorization code.
    OAuthCode {
        /// The authorization code.
        code: String,
        /// Optional PKCE verifier.
        code_verifier: Option<String>,
    },
    /// Token-based authentication (e.g., Bearer token).
    Token(String),
    /// Custom input for extensible methods.
    Custom(serde_json::Value),
    /// MFA Challenge Submission
    MfaChallenge {
        /// The temporary MFA JWT token
        mfa_token: String,
        /// The specific factor input (e.g., Totp or WebAuthnAuthentication)
        challenge_input: Box<AuthInput>,
    },
    /// WebAuthn Passkeys authentication input
    #[cfg(feature = "webauthn")]
    WebAuthnAuthentication {
        /// The local user ID
        user_id: String,
        /// The credential ID of the passkey
        credential_id: String,
        /// The client data JSON from the ceremony
        client_data_json: String,
        /// The authenticator data from the ceremony
        authenticator_data: String,
        /// The signature generated by the key
        signature: String,
        /// Optional user handle
        user_handle: Option<String>,
        /// Optional authentication state serialized as JSON (injected by the server session, not the client)
        #[serde(default)]
        auth_state_json: Option<String>,
    },
    /// Magic-link completion input.
    #[cfg(feature = "magic-link")]
    MagicLink {
        /// The secret from the link the user followed.
        token: String,
        /// The binding value the application recorded when it minted the
        /// link — typically a nonce it set as a cookie. Server-supplied, not
        /// client-supplied: letting the caller name its own binding would
        /// let it satisfy the check it is meant to fail.
        ///
        /// `None` when the application has none to present. A link minted
        /// with [`MagicLinkBinding::AnyContext`](magic_link::MagicLinkBinding::AnyContext)
        /// does not need one; one minted with `SameContext` is rejected
        /// without it.
        binding: Option<String>,
    },
    /// One-time code completion input.
    #[cfg(feature = "otp")]
    Otp {
        /// The subject the application resolved before minting. The challenge
        /// is keyed by this rather than by the code — see
        /// `docs/rfc-011-otp.md` §2.2 for why a short code cannot be the key.
        subject: String,
        /// The digits the user typed.
        code: String,
    },
    /// Recovery code redemption input.
    #[cfg(feature = "recovery-codes")]
    RecoveryCode {
        /// The account redeeming a code — the credential-store key, and the
        /// same id `Engine::authenticate` checks a step-up's continuation
        /// token against.
        user_id: String,
        /// The code as the user typed it. Separators and case are
        /// normalised, so it need not be retyped exactly as printed.
        code: String,
    },
    /// TOTP validation input
    #[cfg(feature = "totp")]
    Totp {
        /// The local user ID
        user_id: String,
        /// The 6-digit TOTP code
        code: String,
    },
}

/// A mechanism used to authenticate a user.
#[async_trait]
pub trait AuthMethod: Send + Sync {
    /// Returns the name of the authentication method.
    fn name(&self) -> &str;

    /// Optional downcast to WebAuthnStarter
    #[cfg(feature = "webauthn")]
    fn as_webauthn_starter(&self) -> Option<&dyn WebAuthnStarter> {
        None
    }

    /// Authenticate a user with the given input.
    async fn authenticate(&self, input: AuthInput) -> Result<Identity, AuthError>;

    /// Check if a given user has enrolled in this authentication method.
    /// Default implementation returns false.
    async fn has_enrolled(&self, _user_id: &str) -> Result<bool, AuthError> {
        Ok(false)
    }

    /// Indicates whether this method provides multi-factor-equivalent security.
    /// If true, users logging in with this method will not be prompted for an additional MFA step.
    /// Default implementation returns false.
    fn is_mfa_equivalent(&self) -> bool {
        false
    }
}

